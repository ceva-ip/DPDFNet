#!/usr/bin/env python3
"""Derive VEX-encoded VNNI kernels without duplicating the assembly algorithms.

The AVX2 pair sums cannot saturate: activations <=254 and |weight|<=63.
Replace only their integer reduction; retain addressing, scales, biases,
floating-point instruction order and ABI from the validated AVX2 sources.
Generated assembly is checked in so a normal CMake build needs no Python.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [
    "src/common/qdot64_fixed_avx2.S",
    "src/common/qdot4pair_fixed_avx2.S",
    "src/models/dpdfnet2_48khz_hr/qaffine64_fused_avx2.S",
    "src/models/dpdfnet2_48khz_hr/qaffine256_fused_avx2.S",
    "src/models/dpdfnet2_48khz_hr/qaffine4pair64_fused_avx2.S",
    "src/models/dpdfnet8_48khz_hr/qaffine64_fused_avx2.S",
]


def convert(source):
    lines = source.read_text().splitlines()
    pending, replaced, removed = {}, {}, set()
    for index, line in enumerate(lines):
        match = re.match(r"\s*(vpmaddubsw|vpmaddwd|vpaddd)\s+(.+)", line)
        if not match:
            continue
        op, operands = match.groups()
        args = [arg.strip() for arg in operands.split(",")]
        assert len(args) == 3, (source, line)
        dst, first, second = args
        if op == "vpmaddubsw":
            assert dst not in pending, (source, "unconsumed temporary", dst)
            pending[dst] = (index, first, second, None)
        elif op == "vpmaddwd" and dst in pending:
            begin, activation, weight, reduction = pending[dst]
            assert first == dst and reduction is None, (source, line)
            pending[dst] = (begin, activation, weight, index)
        elif op == "vpaddd" and second in pending:
            begin, activation, weight, reduction = pending.pop(second)
            assert first == dst and reduction is not None, (source, line)
            # Moving the accumulation to the original multiply must not cross
            # an assignment that overwrites its accumulator.
            for previous in lines[begin + 1:index]:
                written = re.match(r"\s*v\w+\s+(ymm\d+)\s*,", previous)
                assert not written or written.group(1) != dst, (source, previous)
            replaced[begin] = f"    {{vex}} vpdpbusd {dst}, {activation}, {weight}"
            removed.update([reduction, index])
    assert not pending and replaced, (source, pending)
    result = "\n".join(replaced.get(i, line) for i, line in enumerate(lines) if i not in removed)
    result = result.replace("_avx2", "_vnni")
    header = f"/* Generated by tools/generate_vnni.py from {source.relative_to(ROOT)}.\n * Do not edit: regenerate after changing the AVX2 source. */\n"
    return header + result + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for relative in SOURCES:
        source = ROOT / relative
        output = source.with_name(source.name.replace("_avx2", "_vnni"))
        expected = convert(source)
        if args.check:
            if not output.exists() or output.read_text() != expected:
                raise SystemExit(f"Regenerate stale VNNI assembly: {output.relative_to(ROOT)}")
        else:
            output.write_text(expected)


if __name__ == "__main__":
    main()
